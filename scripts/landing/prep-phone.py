"""Key the green screen out of a ChatGPT phone render and emit:
  public/images/landing/phone-shell.webp  (RGBA shell, screen hole transparent, background removed)
  src/components/marketing/landing/phone-config.ts (shell size + 3x3 homography for the live screen)
Usage: python3 -I scripts/landing/prep-phone.py <render.png>
"""
import sys, json
import numpy as np
from PIL import Image

SRC = sys.argv[1]
SCREEN_W, SCREEN_H = 393, 852  # iPhone point size; the live screen is laid out at this size
BG = np.array([253.0, 239.0, 223.0])

im = Image.open(SRC).convert("RGB")
a = np.asarray(im).astype(np.float64)
H, W, _ = a.shape
R, G, B = a[..., 0], a[..., 1], a[..., 2]

# 1) greenness: fraction of pure green mixed with a dark bezel
f = np.clip((G - np.maximum(R, B)) / 247.0, 0, 1)
hole = np.clip((f - 0.08) / 0.84, 0, 1)

# 2) background alpha from distance to the cream backdrop
dist = np.sqrt(((a - BG) ** 2).sum(-1))
bga = np.clip((dist - 14) / 46.0, 0, 1)

alpha = bga * (1 - hole)

# 3) un-premultiply the backdrop out of semi-transparent edge pixels, despill green
rgb = a.copy()
m = (bga > 0) & (bga < 1)
rgb[m] = (a[m] - (1 - bga[m, None]) * BG) / bga[m, None]
rgb = np.clip(rgb, 0, 255)
spill = (rgb[..., 1] > np.maximum(rgb[..., 0], rgb[..., 2]) + 6) & (hole > 0)
rgb[..., 1] = np.where(spill, np.maximum(rgb[..., 0], rgb[..., 2]), rgb[..., 1])

# 4) screen quad from the hole mask: fit 4 edge lines, intersect
mask = f > 0.5
ys, xs = np.where(mask)
x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
w, h = x1 - x0, y1 - y0

def edge_pts(axis, side, lo, hi):
    pts = []
    if axis == "row":  # left/right edge per row
        for y in range(int(y0 + lo * h), int(y0 + hi * h)):
            r = np.where(mask[y])[0]
            if r.size:
                pts.append((r.min() if side == 0 else r.max(), y))
    else:  # top/bottom edge per column
        for x in range(int(x0 + lo * w), int(x0 + hi * w)):
            c = np.where(mask[:, x])[0]
            if c.size:
                pts.append((x, c.min() if side == 0 else c.max()))
    return np.array(pts, float)

def fit(pts, axis):
    # row edges: x = m*y + c ; column edges: y = m*x + c  -> return a,b,c for ax+by=c
    if axis == "row":
        m_, c_ = np.polyfit(pts[:, 1], pts[:, 0], 1)
        res = np.abs(pts[:, 0] - (m_ * pts[:, 1] + c_)).max()
        return (1.0, -m_, c_), res
    m_, c_ = np.polyfit(pts[:, 0], pts[:, 1], 1)
    res = np.abs(pts[:, 1] - (m_ * pts[:, 0] + c_)).max()
    return (-m_, 1.0, c_), res

top_pts = edge_pts("col", 0, 0.3, 0.72)
left, rl = fit(edge_pts("row", 0, 0.2, 0.8), "row")
right, rr = fit(edge_pts("row", 1, 0.2, 0.8), "row")
top, rt = fit(top_pts, "col")
bottom, rb = fit(edge_pts("col", 1, 0.25, 0.7), "col")
print("edge fit max residual px  L%.2f R%.2f T%.2f B%.2f" % (rl, rr, rt, rb))

def inter(l1, l2):
    A = np.array([[l1[0], l1[1]], [l2[0], l2[1]]])
    return np.linalg.solve(A, np.array([l1[2], l2[2]]))

TL, TR = inter(top, left), inter(top, right)
BL, BR = inter(bottom, left), inter(bottom, right)
print("quad", TL, TR, BR, BL)

# 5) crop to the shell
ab = alpha > 0.02
cy, cx = np.where(ab)
pad = 6
cx0, cx1, cy0, cy1 = max(cx.min() - pad, 0), min(cx.max() + pad, W - 1), max(cy.min() - pad, 0), min(cy.max() + pad, H - 1)
out = np.dstack([rgb, alpha * 255]).astype(np.uint8)[cy0 : cy1 + 1, cx0 : cx1 + 1]
Image.fromarray(out, "RGBA").save("public/images/landing/phone-shell.webp", quality=90, method=6)
CW, CH = out.shape[1], out.shape[0]
hm = np.zeros((CH, CW, 4), np.uint8)
hm[..., 3] = (hole * 255).astype(np.uint8)[cy0 : cy1 + 1, cx0 : cx1 + 1]
Image.fromarray(hm, "RGBA").save("public/images/landing/phone-hole.webp", lossless=True)
corners = [(p[0] - cx0, p[1] - cy0) for p in (TL, TR, BR, BL)]

# 6) homography: (0,0),(W,0),(W,H),(0,H) -> corners  (DLT)
src = [(0, 0), (SCREEN_W, 0), (SCREEN_W, SCREEN_H), (0, SCREEN_H)]
rows = []
for (x, y), (X, Y) in zip(src, corners):
    rows.append([x, y, 1, 0, 0, 0, -X * x, -X * y, -X])
    rows.append([0, 0, 0, x, y, 1, -Y * x, -Y * y, -Y])
_, _, vt = np.linalg.svd(np.array(rows, float))
Hm = vt[-1].reshape(3, 3)
Hm = Hm / Hm[2, 2]
# css matrix3d(a,d,0,g, b,e,0,h, 0,0,1,0, c,f,0,1)
m3 = [Hm[0, 0], Hm[1, 0], 0, Hm[2, 0], Hm[0, 1], Hm[1, 1], 0, Hm[2, 1], 0, 0, 1, 0, Hm[0, 2], Hm[1, 2], 0, 1]
cfg = f"""/* Generated by scripts/landing/prep-phone.py. Do not edit by hand. */
export const PHONE = {{
  shellW: {CW},
  shellH: {CH},
  screenW: {SCREEN_W},
  screenH: {SCREEN_H},
  matrix3d: "matrix3d({', '.join(f'{v:.8g}' for v in m3)})",
  corners: {json.dumps([[round(float(a_), 2), round(float(b_), 2)] for a_, b_ in corners])},
}} as const;
"""
open("src/components/marketing/landing/phone-config.ts", "w").write(cfg)
print("shell", CW, CH)
